// Turns deploy/legacy-redirects.json into an nginx include of permanent
// redirects for cloud.gov. A static export emits no HTTP redirects, and
// next.config `redirects()` is unsupported with `output: 'export'`, so moved
// pages redirect at the web server instead. GitHub Pages has no such
// hook and does not get these.
//
// The include lands in out/nginx/conf/includes/, which the staticfile buildpack
// pastes inside `location / { }`. `rewrite ... permanent` is a 301, and
// redirect.conf's `absolute_redirect off` keeps the Location header relative.
//
// Called from build-cloudgov.mjs once the export sits in out/public/, because
// the checks below need the finished page list.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const SOURCE_JSON = "deploy/legacy-redirects.json";
// Lowercase path segments with a trailing slash. Anything else is refused so a
// bad entry never puts whitespace, quotes or semicolons into the nginx config.
export const SAFE_PATH = /^\/[a-z0-9][a-z0-9/._-]*\/$/;

// Escape regex metacharacters so `/citations/mco-1720.1/` matches literally.
function escapeRegex(text) {
  return text.replace(/[.+*?()[\]{}|^$\\]/g, "\\$&");
}

/**
 * @param {{ redirects: { from: string, to: string }[], pageExists: (urlPath: string) => boolean }} input
 * @returns {string} nginx include text
 */
export function buildLegacyRedirects({ redirects, pageExists }) {
  const problems = [];
  const fromCounts = new Map();
  for (const { from } of redirects) {
    fromCounts.set(from, (fromCounts.get(from) ?? 0) + 1);
  }

  for (const { from, to } of redirects) {
    if (!SAFE_PATH.test(from) || !SAFE_PATH.test(to)) {
      problems.push(`unsafe path: ${from} -> ${to}`);
      continue;
    }
    if (from === to) problems.push(`redirects to itself: ${from}`);
    if (fromCounts.get(from) > 1) problems.push(`duplicate from: ${from}`);
    if (fromCounts.has(to)) {
      problems.push(`chain (target is also a from): ${from} -> ${to}`);
    }
    if (pageExists(from)) {
      problems.push(`would shadow a live page: ${from}`);
    }
    if (!pageExists(to)) {
      problems.push(`target page missing from export: ${from} -> ${to}`);
    }
  }

  if (problems.length > 0) {
    const unique = [...new Set(problems)];
    throw new Error(
      `Invalid legacy redirects (${unique.length}):\n  ${unique.join("\n  ")}`
    );
  }

  const rules = redirects.map(
    ({ from, to }) =>
      `rewrite ^${escapeRegex(from.slice(0, -1))}/?$ ${to} permanent;`
  );
  return [
    `# Generated by scripts/build-legacy-redirects.mjs from ${SOURCE_JSON}.`,
    "# Do not edit. Change the JSON and rebuild.",
    ...rules,
    "",
  ].join("\n");
}

// Writes the include for a built export. publicDir is the served root
// (out/public); includeDir is out/nginx/conf/includes. Returns the rule count.
export function writeLegacyRedirects({ publicDir, includeDir }) {
  const { redirects } = JSON.parse(readFileSync(SOURCE_JSON, "utf8"));
  const text = buildLegacyRedirects({
    redirects,
    pageExists: (urlPath) =>
      existsSync(path.join(publicDir, urlPath, "index.html")),
  });
  writeFileSync(path.join(includeDir, "legacy-redirects.conf"), text);
  return redirects.length;
}
