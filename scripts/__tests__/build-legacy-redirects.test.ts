import fs from "node:fs";
import path from "node:path";
import { describe, expect, it } from "vitest";
import { SAFE_PATH, buildLegacyRedirects } from "../build-legacy-redirects.mjs";

const live = new Set(["/new/", "/other/", "/live/"]);
const pageExists = (p: string) => live.has(p);
const build = (redirects: { from: string; to: string }[]) =>
  buildLegacyRedirects({ redirects, pageExists });

describe("buildLegacyRedirects output", () => {
  it("emits one rewrite per entry with an optional trailing slash", () => {
    const text = build([{ from: "/old/page/", to: "/new/" }]);
    expect(text).toContain("rewrite ^/old/page/?$ /new/ permanent;");
  });

  it("escapes regex metacharacters so dots match literally", () => {
    const text = build([{ from: "/citations/mco-1720.1/", to: "/new/" }]);
    expect(text).toContain(
      "rewrite ^/citations/mco-1720\\.1/?$ /new/ permanent;"
    );
  });

  it("marks the file as generated", () => {
    const text = build([{ from: "/old/", to: "/new/" }]);
    expect(text).toMatch(/^# Generated by scripts\/build-legacy-redirects\.mjs/);
    expect(text).toContain("deploy/legacy-redirects.json");
    expect(text).toContain("Do not edit");
  });
});

describe("buildLegacyRedirects validation", () => {
  it("rejects a target missing from the export", () => {
    expect(() => build([{ from: "/old/", to: "/gone/" }])).toThrow(
      /target page missing.*\/old\/ -> \/gone\//
    );
  });

  it("rejects a from that is a live page", () => {
    expect(() => build([{ from: "/live/", to: "/new/" }])).toThrow(
      /shadow a live page: \/live\//
    );
  });

  it("rejects duplicate from entries", () => {
    expect(() =>
      build([
        { from: "/old/", to: "/new/" },
        { from: "/old/", to: "/other/" },
      ])
    ).toThrow(/duplicate from: \/old\//);
  });

  it("rejects from equal to to", () => {
    expect(() => build([{ from: "/new/", to: "/new/" }])).toThrow(
      /to itself: \/new\//
    );
  });

  it("rejects chains", () => {
    expect(() =>
      build([
        { from: "/a/", to: "/b/" },
        { from: "/b/", to: "/new/" },
      ])
    ).toThrow(/chain.*\/a\/ -> \/b\//);
  });

  it("rejects unsafe paths", () => {
    for (const from of ["/Old/", "/old", "/old page/", "/old;x/", "/"]) {
      expect(() => build([{ from, to: "/new/" }])).toThrow(/unsafe path/);
    }
  });
});

describe("deploy/legacy-redirects.json", () => {
  const file = path.join(process.cwd(), "deploy", "legacy-redirects.json");
  const { redirects } = JSON.parse(fs.readFileSync(file, "utf8")) as {
    redirects: { from: string; to: string }[];
  };

  it("has entries", () => {
    expect(redirects.length).toBeGreaterThan(0);
  });

  it("uses only safe paths", () => {
    const bad = redirects.filter(
      (r) => !SAFE_PATH.test(r.from) || !SAFE_PATH.test(r.to)
    );
    expect(bad).toEqual([]);
  });

  it("has no duplicates, self-redirects or chains", () => {
    const froms = new Set(redirects.map((r) => r.from));
    expect(froms.size).toBe(redirects.length);
    expect(redirects.filter((r) => r.from === r.to)).toEqual([]);
    expect(redirects.filter((r) => froms.has(r.to))).toEqual([]);
  });
});
